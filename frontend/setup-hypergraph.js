#!/usr/bin/env node

/**
 * Hypergraph Setup Script
 * This script helps you configure your Hypergraph space ID
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

console.log('🚀 Hypergraph Setup Script');
console.log('==========================\n');

console.log('This script will help you configure your Hypergraph space ID.\n');

console.log('To get a space ID:');
console.log('1. Visit https://thegraph.com/hypergraph');
console.log('2. Create a new space or use an existing one');
console.log('3. Copy the space ID from your space dashboard\n');

rl.question('Enter your Hypergraph space ID: ', (spaceId) => {
  if (!spaceId || spaceId.trim() === '') {
    console.log('❌ No space ID provided. Please run the script again with a valid space ID.');
    rl.close();
    return;
  }

  const envContent = `# Hypergraph Configuration
# Generated by setup script
VITE_HYPERGRAPH_SPACE_ID=${spaceId.trim()}

# To get a space ID:
# 1. Visit https://thegraph.com/hypergraph
# 2. Create a new space or use an existing one
# 3. Copy the space ID and paste it here
# 4. Restart your development server
`;

  const envPath = path.join(__dirname, '.env');
  
  try {
    fs.writeFileSync(envPath, envContent);
    console.log('✅ Successfully created .env file with your space ID!');
    console.log('🔄 Please restart your development server to apply the changes.');
    console.log('\nNext steps:');
    console.log('1. Run: npm run dev');
    console.log('2. Open your app and navigate to the Hypergraph Dashboard');
    console.log('3. You should now be able to create strategies and trades!');
  } catch (error) {
    console.log('❌ Error creating .env file:', error.message);
    console.log('Please create the .env file manually with the following content:');
    console.log(envContent);
  }
  
  rl.close();
});
